#!/bin/sh
# Keeps the C23 crypto core's generic C names out of the daemon's link namespace.
#
# The vendored Z23 code exports names such as blake2b_init, blake2b_update,
# blake2b_final, sha256_init, fr_add. libsodium.a exports blake2b_init,
# blake2b_update, blake2b_final, blake2b ... as well (its reference BLAKE2b),
# with a different state layout. In a static link the first definition the
# linker meets wins for BOTH callers, or the link fails with "multiple
# definition", depending on which archive members are pulled. Either libsodium's
# crypto_generichash (Equihash, note encryption, sighash) or the C23 core would
# then run the other one's function. src/c23/vendor is verbatim and is never
# edited, so every object of libzcl_c23.a is compiled with
#   -include src/c23/glue/zcl_c23_symbol_prefix.h
# which #defines each global name of the core to zc23_<name>.
#
# usage: symbol-prefix.sh check <nm> <libzcl_c23.a>
#            Fails unless every defined global symbol of the archive starts with
#            librustzcash_, zcl_c23_, zcl_c23h_, zcl_token_guard_, zcl_tor_, zcl_keyfile_ or zc23_. Run by the build before any
#            program links the archive.
#        symbol-prefix.sh gen <nm> <libzcl_c23.a> <header>
#            Rewrites <header> from the archive. Idempotent: works on an archive
#            built with or without the current header. Run it after re-vendoring
#            when `check` reports a new unprefixed name, then rebuild.
set -u
mode=${1:-}; nm=${2:-}; lib=${3:-}
[ -n "$mode" ] && [ -n "$nm" ] && [ -f "$lib" ] || {
    echo "usage: $0 check <nm> <archive> | gen <nm> <archive> <header>" >&2; exit 2; }

# Defined external symbols, one per line. Mach-O prefixes every C name with "_".
# Names starting with "." are not C identifiers (PE/COFF .refptr.<sym> COMDAT
# pointers, section symbols) and cannot be defined by anyone else's C code.
globals() {
    $nm -g "$lib" 2>/dev/null | awk 'NF==3 && $2 ~ /^[A-TV-Z]$/ && substr($3, 1, 1) != "." {print $3}' | sort -u >"$1"
    if [ -s "$1" ] && ! grep -q -v '^_' "$1"; then
        sed 's/^_//' "$1" >"$1.s" && mv "$1.s" "$1"
    fi
    [ -s "$1" ]
}

tmp=${TMPDIR:-/tmp}/zc23-symprefix.$$
trap 'rm -f "$tmp" "$tmp".*' EXIT INT TERM
globals "$tmp" || { echo "symbol-prefix: no symbols read from $lib" >&2; exit 2; }

case "$mode" in
check)
    bad=$(grep -v -E '^(librustzcash_|zcl_c23_|zcl_c23h_|zcl_token_guard_|zcl_tor_|zcl_keyfile_|zc23_)' "$tmp")
    if [ -n "$bad" ]; then
        echo "symbol-prefix: FAIL $lib exports unprefixed names (would collide in a static link):" >&2
        echo "$bad" | sed 's/^/  /' | head -40 >&2
        echo "symbol-prefix: regenerate src/c23/glue/zcl_c23_symbol_prefix.h (symbol-prefix.sh gen) and rebuild" >&2
        exit 1
    fi
    echo "symbol-prefix: OK $lib ($(wc -l <"$tmp" | tr -d ' ') global symbols, all librustzcash_/zcl_c23_/zcl_c23h_/zcl_token_guard_/zcl_tor_/zcl_keyfile_/zc23_)"
    ;;
gen)
    hdr=${4:-}
    [ -n "$hdr" ] || { echo "usage: $0 gen <nm> <archive> <header>" >&2; exit 2; }
    # Names the current header already renames (so zc23_<name> maps back to <name>).
    : >"$tmp.old"
    [ -f "$hdr" ] && sed -n 's/^#define \([A-Za-z_][A-Za-z0-9_]*\) zc23_\1$/\1/p' "$hdr" | sort -u >"$tmp.old"
    awk -v oldf="$tmp.old" '
        BEGIN { while ((getline l < oldf) > 0) old[l] = 1 }
        /^(librustzcash_|zcl_c23_|zcl_token_guard_|zcl_tor_|zcl_keyfile_)/ { next }
        /^zc23_/ { b = substr($0, 6); if (b in old) print b; next }
        { print }' "$tmp" | sort -u >"$tmp.names"
    {
        echo "/* GENERATED by src/c23/tools/symbol-prefix.sh gen. Do not edit by hand."
        echo " *"
        echo " * Force-included (-include) into every object of libzcl_c23.a and into"
        echo " * anything that calls the core's internal functions directly (src/c23/test)."
        echo " * Each global C name of the core is renamed to zc23_<name>, so it cannot"
        echo " * collide with libsodium / OpenSSL / zclassicd names in the static link"
        echo " * (libsodium.a exports blake2b_init, blake2b_update, blake2b_final, ...)."
        echo " * The public ABI (librustzcash_*, zcl_c23_*) is not renamed. */"
        echo "#ifndef ZCL_C23_SYMBOL_PREFIX_H"
        echo "#define ZCL_C23_SYMBOL_PREFIX_H"
        sed 's/.*/#define & zc23_&/' "$tmp.names"
        echo "#endif"
    } >"$hdr.new" && mv "$hdr.new" "$hdr"
    echo "symbol-prefix: wrote $hdr ($(wc -l <"$tmp.names" | tr -d ' ') names)"
    ;;
*)
    echo "symbol-prefix: unknown mode $mode" >&2; exit 2 ;;
esac
